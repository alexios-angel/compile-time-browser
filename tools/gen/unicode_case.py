#!/usr/bin/env python3
"""Generate Core's Unicode 17 default case mapping tables.

    python3 tools/gen/unicode_case.py > ctbrowser/lib/Core/case_mapping.inc

The tables behind ctbrowser::unicode_case (core/unicode_case.hpp), which
String.prototype.toLowerCase/toUpperCase and the native runtime both call:

  * lower_runs/upper_runs: UnicodeData.txt's simple mappings (fields 13 and
    12), as runs of code points first..last, every stride-th of which maps to
    itself plus delta. A code point with a special entry is left out.
  * lower_special/upper_special: SpecialCasing.txt's unconditional entries
    whose mapping is not that code point's simple one (up to three code points).
  * cased_ranges/case_ignorable_ranges: DerivedCoreProperties.txt's Cased and
    Case_Ignorable, which Final_Sigma (Unicode table 3-17) needs. They are the
    same ranges the regular-expression tables give \\p{Cased} and
    \\p{Case_Ignorable} (tools/gen/unicode_properties.py), so the two cannot
    disagree about one code point.

Every file is fetched from the pinned release and its SHA-256 checked.
"""

import hashlib
import sys
import urllib.request

VERSION = "17.0.0"
HASHES = {
    "UnicodeData.txt": "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
    "SpecialCasing.txt": "efc25faf19de21b92c1194c111c932e03d2a5eaf18194e33f1156e96de4c9588",
    "DerivedCoreProperties.txt": "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08",
}


def fields(name):
    """Fetch a pinned UCD file, verify its SHA-256 and yield each data line's
    semicolon-separated fields."""
    with urllib.request.urlopen(
        f"https://www.unicode.org/Public/{VERSION}/ucd/{name}", timeout=30
    ) as response:
        data = response.read()
    if hashlib.sha256(data).hexdigest() != HASHES[name]:
        raise ValueError(f"{name}: pinned Unicode checksum changed")
    for line in data.decode("utf-8").splitlines():
        line = line.partition("#")[0].strip()
        if line:
            yield [part.strip() for part in line.split(";")]


def hexed(cp):
    return f"0x{cp:04X}"


def runs(mapping):
    """Compress {cp: mapped} into (first, last, stride, delta) runs that do not
    overlap: a run continues only while the next mapped code point is exactly
    one stride on and has the same delta."""
    points = sorted(mapping)
    out = []
    i = 0
    while i < len(points):
        first = points[i]
        delta = mapping[first] - first
        stride, last = 1, first
        if i + 1 < len(points):
            step = points[i + 1] - first
            if step in (1, 2) and mapping[points[i + 1]] - points[i + 1] == delta:
                stride = step
        j = i + 1
        while j < len(points) and points[j] == last + stride and mapping[points[j]] - points[j] == delta:
            last = points[j]
            j += 1
        out.append((first, last, stride, delta))
        i = j
    return out


def ranges(points):
    """Sorted, disjoint, maximal [lo, hi] pairs of a set of code points."""
    out = []
    for cp in sorted(points):
        if out and out[-1][1] + 1 == cp:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def main():
    lower, upper = {}, {}
    for row in fields("UnicodeData.txt"):
        cp = int(row[0], 16)
        if row[12]:
            upper[cp] = int(row[12], 16)
        if row[13]:
            lower[cp] = int(row[13], 16)
    lower_special, upper_special = {}, {}
    for row in fields("SpecialCasing.txt"):
        # code; lower; title; upper; (condition_list;)? - unconditional only.
        if len(row) > 4 and row[4]:
            continue
        cp = int(row[0], 16)
        for column, simple, special in ((1, lower, lower_special), (3, upper, upper_special)):
            to = [int(part, 16) for part in row[column].split()]
            if to != [simple.get(cp, cp)]:
                special[cp] = to
    properties = {"Cased": set(), "Case_Ignorable": set()}
    for row in fields("DerivedCoreProperties.txt"):
        if row[1] in properties:
            span = row[0].split("..")
            properties[row[1]].update(range(int(span[0], 16), int(span[-1], 16) + 1))

    print("// GENERATED by tools/gen/unicode_case.py - do not edit.")
    print(f"// Unicode {VERSION}: UnicodeData.txt simple mappings + unconditional")
    print("// SpecialCasing.txt; Final_Sigma is computed, not tabled.")
    print(f"// UnicodeData.txt SHA256: {HASHES['UnicodeData.txt']}")
    print(f"// SpecialCasing.txt SHA256: {HASHES['SpecialCasing.txt']}")
    print(f"// DerivedCoreProperties.txt SHA256: {HASHES['DerivedCoreProperties.txt']}")
    print("// Unicode data: Copyright (c) 1991-2026 Unicode, Inc., under the Unicode")
    print("// License V3 (https://www.unicode.org/license.txt).")
    print("// clang-format off")
    for name, simple, special in (
        ("lower", lower, lower_special),
        ("upper", upper, upper_special),
    ):
        mapped = {cp: to for cp, to in simple.items() if cp not in special}
        print(f"constexpr case_run {name}_runs[] = {{")
        for first, last, stride, delta in runs(mapped):
            print(f"    {{{hexed(first)}, {hexed(last)}, {stride}, {delta}}},")
        print("};")
        print(f"constexpr case_special {name}_special[] = {{")
        for cp in sorted(special):
            to = (special[cp] + [0, 0, 0])[:3]
            print(f"    {{{hexed(cp)}, {{{', '.join(hexed(each) for each in to)}}}}},")
        print("};")
    for name, prop in (("cased", "Cased"), ("case_ignorable", "Case_Ignorable")):
        print(f"constexpr case_range {name}_ranges[] = {{")
        for lo, hi in ranges(properties[prop]):
            print(f"    {{{hexed(lo)}, {hexed(hi)}}},")
        print("};")
    print("// clang-format on")
    total = sum(len(p) for p in properties.values())
    print(f"unicode_case: {len(lower)} lower, {len(upper)} upper, {total} property points", file=sys.stderr)


if __name__ == "__main__":
    main()
