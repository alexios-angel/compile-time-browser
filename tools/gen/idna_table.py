#!/usr/bin/env python3
"""Regenerate ctbrowser/lib/Shell/net/idna_table.inc - the UTS #46 tables the
URL parser's `domain to ASCII` runs on.

Four tables, all of them DATA published by Unicode:

  * IdnaMappingTable.txt, collapsed to the four statuses the URL Standard's
    parameters leave (UseSTD3ASCIIRules false, Transitional_Processing false):
    a `deviation` is valid, a `disallowed_STD3_valid` is valid and a
    `disallowed_STD3_mapped` is mapped. Collapsing here rather than at run time
    is what keeps the lookup one binary search and no flags.
  * General_Category=M, for "a label must not begin with a combining mark".
  * Canonical_Combining_Class=9 (Virama), for the first ContextJ rule.
  * Joining_Type, for the second: (L|D) T* ZWNJ T* (R|D).

    python3 tools/gen/idna_table.py > ctbrowser/lib/Shell/net/idna_table.inc

Hand-typing 8,000 ranges is how a wrong one gets in and stays in, so this
fetches them. Everything comes from unicode.org except the two derived
properties, which Python's own unicodedata already carries - its Unicode
version and the fetched files' may differ by a release, which moves a handful
of recently assigned code points and nothing that WPT tests.
"""

import sys
import unicodedata
import urllib.request

IDNA_URL = "https://www.unicode.org/Public/idna/latest/IdnaMappingTable.txt"
JOINING_URL = "https://www.unicode.org/Public/UNIDATA/extracted/DerivedJoiningType.txt"

VALID, MAPPED, IGNORED, DISALLOWED = 0, 1, 2, 3


def fetch(url):
    with urllib.request.urlopen(url) as response:
        # split("\n") and NOT splitlines(): a description column can hold
        # U+0085, U+2028 or U+2029, which splitlines() treats as a break.
        return response.read().decode("utf-8").split("\n")


def rows_of(lines):
    """(first, last, [fields...]) for every data line of a UCD file."""
    for line in lines:
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        fields = [f.strip() for f in line.split(";")]
        span = fields[0].split("..")
        yield int(span[0], 16), int(span[-1], 16), fields[1:]


def idna_table():
    rows = []
    for first, last, fields in rows_of(fetch(IDNA_URL)):
        status = fields[0]
        mapping = ()
        if status in ("valid", "disallowed_STD3_valid", "deviation"):
            # A deviation is VALID with Transitional_Processing false: the
            # sharp s stays a sharp s and ZWJ stays a ZWJ.
            kind = VALID
        elif status in ("mapped", "disallowed_STD3_mapped"):
            kind = MAPPED
            mapping = tuple(int(c, 16) for c in fields[1].split()) if len(fields) > 1 else ()
            if not mapping:
                kind = IGNORED
        elif status == "ignored":
            kind = IGNORED
        else:
            kind = DISALLOWED
        rows.append((first, last, kind, mapping))
    rows.sort()
    merged = []
    for row in rows:
        if (
            merged
            and merged[-1][2] == row[2]
            and not merged[-1][3]
            and not row[3]
            and merged[-1][1] + 1 == row[0]
        ):
            merged[-1] = (merged[-1][0], row[1], row[2], ())
        else:
            merged.append(row)
    return merged


def ranges_where(predicate):
    out = []
    for cp in range(0x110000):
        if not predicate(cp):
            continue
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def joining_ranges():
    kinds = {}
    for first, last, fields in rows_of(fetch(JOINING_URL)):
        if fields[0] in ("L", "D", "R", "T"):
            for cp in range(first, last + 1):
                kinds[cp] = fields[0]
    out = []
    for cp in sorted(kinds):
        if out and out[-1][1] == cp - 1 and out[-1][2] == kinds[cp]:
            out[-1][1] = cp
        else:
            out.append([cp, cp, kinds[cp]])
    return out


def print_pairs(name, pairs, comment):
    print("// %s" % comment)
    print("constexpr char32_t %s[][2] = {" % name)
    for at in range(0, len(pairs), 4):
        row = "".join("{0x%X, 0x%X}, " % (a, b) for a, b in pairs[at : at + 4])
        print("    " + row.rstrip())
    print("};")
    print()


def main():
    table = idna_table()
    mappings = []
    print("// GENERATED by tools/gen/idna_table.py - do not edit.")
    print("// clang-format off")
    print()
    print("// IdnaMappingTable.txt, collapsed to the four statuses the URL")
    print("// Standard's parameters leave. A code point in no range is disallowed.")
    print("constexpr idna_range idna_ranges[] = {")
    for first, last, kind, mapping in table:
        at = len(mappings)
        mappings.extend(mapping)
        print("    {0x%X, 0x%X, %d, %d, %d}," % (first, last, kind, at, len(mapping)))
    print("};")
    print()
    print("// The mapped code points themselves, indexed by idna_range::map_at.")
    print("constexpr char32_t idna_mappings[] = {")
    for at in range(0, len(mappings), 8):
        print("    " + "".join("0x%X, " % cp for cp in mappings[at : at + 8]).rstrip())
    print("};")
    print()
    print_pairs(
        "combining_mark_ranges",
        [tuple(r) for r in ranges_where(lambda cp: unicodedata.category(chr(cp))[0] == "M")],
        "General_Category=M: a label may not BEGIN with one (4.1 criterion 4).",
    )
    print_pairs(
        "virama_ranges",
        [tuple(r) for r in ranges_where(lambda cp: unicodedata.combining(chr(cp)) == 9)],
        "Canonical_Combining_Class=Virama, the first ContextJ rule.",
    )
    print("// Joining_Type L, D, R and T; anything else is U (the second")
    print("// ContextJ rule: (L|D) T* ZWNJ T* (R|D)).")
    print("constexpr joining_range joining_ranges[] = {")
    for first, last, kind in joining_ranges():
        print("    {0x%X, 0x%X, '%s'}," % (first, last, kind))
    print("};")
    print("// clang-format on")
    return 0


if __name__ == "__main__":
    sys.exit(main())
