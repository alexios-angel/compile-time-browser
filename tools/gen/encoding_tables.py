#!/usr/bin/env python3
"""Regenerate the single-byte decoder indexes in
ctbrowser/lib/Shell/bindings/window/encoding_tables.inc.

The Encoding Standard publishes one index per legacy single-byte encoding as a
plain text file; each maps the 128 bytes 0x80-0xFF to a code point, with gaps
where a byte has no mapping. They are DATA - hand-typing 3,456 code points is
how a wrong one gets in and stays in - so this fetches them and prints the
table. Run it when the Standard republishes an index:

    python3 tools/gen/encoding_tables.py > \\
        ctbrowser/lib/Shell/bindings/window/encoding_tables.inc

U+0000 in a row means "this byte has no mapping": the decoder's error, which
is U+FFFD or, when fatal, a TypeError. No index maps a byte to U+0000, so the
sentinel costs nothing.
"""

import sys
import urllib.request

BASE = "https://encoding.spec.whatwg.org/index-{}.txt"

# Every single-byte encoding of the Encoding Standard, in the order its table
# lists them. `iso-8859-8-i` shares iso-8859-8's index and is an alias, not a
# row of its own.
ENCODINGS = [
    "ibm866",
    "iso-8859-2",
    "iso-8859-3",
    "iso-8859-4",
    "iso-8859-5",
    "iso-8859-6",
    "iso-8859-7",
    "iso-8859-8",
    "iso-8859-10",
    "iso-8859-13",
    "iso-8859-14",
    "iso-8859-15",
    "iso-8859-16",
    "koi8-r",
    "koi8-u",
    "macintosh",
    "windows-874",
    "windows-1250",
    "windows-1251",
    "windows-1252",
    "windows-1253",
    "windows-1254",
    "windows-1255",
    "windows-1256",
    "windows-1257",
    "windows-1258",
    "x-mac-cyrillic",
]


def index_of(name):
    """The 128 code points of one index, 0 where the byte has no mapping."""
    out = [0] * 128
    with urllib.request.urlopen(BASE.format(name)) as response:
        # split("\n") and NOT splitlines(): the description column holds the
        # mapped character itself, and U+0085, U+2028 and U+2029 are line
        # breaks to splitlines() but not to the file.
        for line in response.read().decode("utf-8").split("\n"):
            # A comment line only ever starts with "#"; the description column
            # of a row can hold one as the mapped character itself.
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            pointer, code_point = line.split()[:2]
            out[int(pointer)] = int(code_point, 16)
    return out


def main():
    print("// GENERATED by tools/gen/encoding_tables.py - do not edit.")
    print("// The Encoding Standard's single-byte indexes: bytes 0x80-0xFF, one")
    print("// row per encoding, U+0000 where the byte has no mapping.")
    print("// clang-format off")
    print("constexpr std::u16string_view single_byte_indexes[] = {")
    for name in ENCODINGS:
        row = "".join("\\u%04X" % cp for cp in index_of(name))
        print('    u"%s", // %s' % (row, name))
    print("};")
    print("// clang-format on")
    return 0


if __name__ == "__main__":
    sys.exit(main())
