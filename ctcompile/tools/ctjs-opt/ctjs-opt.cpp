//===- ctcompile/tools/ctjs-opt/ctjs-opt.cpp - The CTJS optimizer driver --===//
//
// A thin MlirOptMain wrapper that registers ctcompile's dialects and passes,
// so every dialect and pass can be exercised from lit tests.
//
//===----------------------------------------------------------------------===//
#include <ctcompile/Support/MLIRContextSetup.hpp>

#include "ctcompile/CTJS/Transforms/Passes.h"

#include "ctcompile/CTNative/Transforms/Passes.h"
#include "mlir/Conversion/Passes.h"
#include "mlir/IR/DialectRegistry.h"
#include "mlir/Tools/mlir-opt/MlirOptMain.h"
#include "mlir/Transforms/Passes.h"

int main(int argc, char ** argv) {
    mlir::DialectRegistry registry;
    ctcompile::registerCTCompileDialects(registry);
    // Generated by -gen-pass-decls, which makes --ctjs-lower-to-emitc a flag
    // without any hand-written registration.
    ctcompile::ctjs::registerCTJSPasses();
    // The ctnative (native-tier) passes, registered the same generated way.
    ctcompile::ctnative::registerCTNativePasses();
    // Register the upstream conversions used by the native and boxed pipelines:
    //
    //   --lift-cf-to-scf      cf.br/cf.cond_br -> scf.if/scf.while
    //   --convert-scf-to-emitc  scf -> emitc.if/emitc.for
    //   --convert-scf-to-cf  specialized structured CTJS -> boxed CFG
    //
    // registerConversionPasses() would pull every backend into the link,
    // including AMDGPU, ArmSME and SPIR-V, which these pipelines do not use.
    mlir::registerLiftControlFlowToSCFPass();
    mlir::registerSCFToEmitC();
    mlir::registerSCFToControlFlowPass();
    // arith -> emitc, because --ctjs-lift-to-scf encodes its edge multiplexers
    // as arith i32 flags.
    mlir::registerConvertArithToEmitC();
    // The canonicalizer runs between the native lowering and the scf
    // conversion: it drops the values the lowering leaves dead (the undefined
    // a top level returns, an unused lift multiplexer result) that -Werror
    // would otherwise reject in the emitted C++.
    mlir::registerCanonicalizerPass();
    mlir::registerCSEPass();
    return mlir::asMainReturnCode(
        mlir::MlirOptMain(argc, argv, "CTJS optimizer driver\n", registry));
}
