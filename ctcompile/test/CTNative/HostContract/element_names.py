#!/usr/bin/env python3
"""Re-enumerate the VM's element property names; fail on any difference.

Element facts (ClassInitialization/Inheritance.cpp) read a constant key the VM's
element binding never defines as undefined. The binding's surface is spread
over lib/Shell/bindings/element/, so the name set is enumerated from the VM
itself: one element per tag of every interface in interface_table (parsed
from interfaces.cpp), plus an unknown tag, a custom-element name and SVG,
MathML and other-namespace elements, each walked from the element through
its whole prototype chain with Object.getOwnPropertyNames. --write
regenerates ElementNames.inc.
"""

import argparse
from pathlib import Path
import re
import subprocess

HEADER = """\
// GENERATED by ctcompile/test/CTNative/HostContract/element_names.py --write.
// Every own and prototype-chain property name a ctbrowser VM element has, for
// one element of each interface in interface_table plus unknown, custom, SVG,
// MathML and other-namespace elements (ctcompile-test-native-reference --page).
// Bytewise sorted; element-names.test re-enumerates and fails on any difference.
"""

PAGE = """<!doctype html><html><head></head><body>
<form id="form"><input name="probe"></form>
<select id="select" name="probe"><option>a</option></select>
<script>
const names = new Set();
const add = (element) => {
  for (let at = element; at !== null; at = Object.getPrototypeOf(at)) {
    for (const name of Object.getOwnPropertyNames(at)) names.add(name);
  }
};
for (const tag of TAGS) add(document.createElement(tag));
for (const element of document.querySelectorAll('*')) add(element);
add(document.createElement('blink'));
add(document.createElement('x-y'));
add(document.createElementNS('http://www.w3.org/2000/svg', 'rect'));
add(document.createElementNS('http://www.w3.org/1998/Math/MathML', 'mi'));
add(document.createElementNS('urn:other', 'other'));
// A named or indexed getter would answer keys no enumeration lists.
for (const id of ['form', 'select']) {
  const element = document.getElementById(id);
  if (element.probe !== undefined || element[0] !== undefined) {
    throw new Error(id + ' answers a named or indexed property');
  }
}
for (const name of names) console.log(name);
</script></body></html>
"""


def interface_tags(source):
    table = re.search(r"interface_table\[\] = \{(.*?)\n\};", source, re.S)
    if not table:
        raise RuntimeError("interfaces.cpp lost its interface_table")
    rows = re.findall(r"\{([^{}]*)\}", re.sub(r"//[^\n]*", "", table[1]))
    tags = []
    for row in rows:
        literals = re.findall(r'"([^"]*)"', row)
        tags += "".join(literals[2:]).split()
    if len(rows) < 80 or "div" not in tags or "h6" not in tags:
        raise RuntimeError(f"interface_table parse lost rows: {len(rows)} rows, {len(tags)} tags")
    return tags


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reference", required=True)
    parser.add_argument("--monorepo", type=Path, required=True)
    parser.add_argument("--work", type=Path, required=True)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    table = args.monorepo / "ctbrowser/lib/Shell/bindings/element/interfaces.cpp"
    data = (
        args.monorepo / "ctcompile/lib/CTNative/HostContract/ClassInitialization/ElementNames.inc"
    )
    tags = interface_tags(table.read_text())
    args.work.mkdir(parents=True, exist_ok=True)
    page = args.work / "element-names.html"
    page.write_text(PAGE.replace("TAGS", repr(sorted(set(tags)))))
    result = subprocess.run(
        [args.reference, "--page", str(page)], capture_output=True, text=True, check=False
    )
    if result.returncode:
        raise RuntimeError(f"element enumeration failed: {result.stderr}")
    names = sorted(set(result.stdout.splitlines()))
    if "nodeType" not in names or any(not name.isascii() or '"' in name for name in names):
        raise RuntimeError("element enumeration lost nodeType or printed a non-ASCII name")
    text = HEADER + "".join(f'"{name}",\n' for name in names)
    if args.write:
        data.write_text(text)
    elif data.read_text() != text:
        old = set(re.findall(r'^"([^"]*)",$', data.read_text(), re.M))
        raise RuntimeError(
            f"ElementNames.inc is stale: added {sorted(set(names) - old)}, "
            f"removed {sorted(old - set(names))}; regenerate with element_names.py --write"
        )
    print(f"element names: {len(tags)} interface tags, {len(names)} names")


if __name__ == "__main__":
    main()
